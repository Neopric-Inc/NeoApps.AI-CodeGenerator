CREATE TABLE plans (
  plan_id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  monthly_price DECIMAL(10,2) NOT NULL,
  seats_included INT NOT NULL DEFAULT 1,
  createdBy VARCHAR(255) NOT NULL, modifiedBy VARCHAR(255) NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, modifiedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  isActive TINYINT(1) NOT NULL DEFAULT '1'
);
CREATE TABLE accounts (
  account_id INT AUTO_INCREMENT PRIMARY KEY,
  company_name VARCHAR(200) NOT NULL,
  industry VARCHAR(100),
  status VARCHAR(30) NOT NULL DEFAULT 'onboarding',
  createdBy VARCHAR(255) NOT NULL, modifiedBy VARCHAR(255) NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, modifiedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  isActive TINYINT(1) NOT NULL DEFAULT '1'
);
CREATE TABLE contacts (
  contact_id INT AUTO_INCREMENT PRIMARY KEY,
  account_id INT NOT NULL,
  full_name VARCHAR(150) NOT NULL,
  email VARCHAR(200) NOT NULL,
  is_primary TINYINT(1) NOT NULL DEFAULT '0',
  createdBy VARCHAR(255) NOT NULL, modifiedBy VARCHAR(255) NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, modifiedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  isActive TINYINT(1) NOT NULL DEFAULT '1',
  FOREIGN KEY (account_id) REFERENCES accounts(account_id)
);
CREATE TABLE subscriptions (
  subscription_id INT AUTO_INCREMENT PRIMARY KEY,
  account_id INT NOT NULL,
  plan_id INT NOT NULL,
  billing_cycle VARCHAR(20) NOT NULL DEFAULT 'monthly',
  start_date DATE NOT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'active',
  createdBy VARCHAR(255) NOT NULL, modifiedBy VARCHAR(255) NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, modifiedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  isActive TINYINT(1) NOT NULL DEFAULT '1',
  FOREIGN KEY (account_id) REFERENCES accounts(account_id),
  FOREIGN KEY (plan_id) REFERENCES plans(plan_id)
);
