-- FacilityMap: apartment buildings drawn as a live 3D floor plan, coloured by each unit's worst open issue.
CREATE TABLE buildings (
  building_id INT AUTO_INCREMENT PRIMARY KEY,
  building_name VARCHAR(100) NOT NULL,
  address VARCHAR(200),
  site_x DECIMAL(6,1) NOT NULL DEFAULT 0,
  site_z DECIMAL(6,1) NOT NULL DEFAULT 0,
  createdBy VARCHAR(255) NOT NULL,
  modifiedBy VARCHAR(255) NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  modifiedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  isActive TINYINT(1) NOT NULL DEFAULT '1'
);

CREATE TABLE floors (
  floor_id INT AUTO_INCREMENT PRIMARY KEY,
  building_id INT NOT NULL,
  level INT NOT NULL,
  floor_label VARCHAR(40) NOT NULL,
  createdBy VARCHAR(255) NOT NULL,
  modifiedBy VARCHAR(255) NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  modifiedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  isActive TINYINT(1) NOT NULL DEFAULT '1',
  FOREIGN KEY (building_id) REFERENCES buildings(building_id)
);

CREATE TABLE units (
  unit_id INT AUTO_INCREMENT PRIMARY KEY,
  floor_id INT NOT NULL,
  unit_label VARCHAR(40) NOT NULL,
  unit_kind VARCHAR(20) NOT NULL DEFAULT 'Apartment',
  bedrooms INT,
  plan_x DECIMAL(5,1) NOT NULL DEFAULT 0,
  plan_z DECIMAL(5,1) NOT NULL DEFAULT 0,
  plan_w DECIMAL(5,1) NOT NULL DEFAULT 6,
  plan_d DECIMAL(5,1) NOT NULL DEFAULT 5,
  createdBy VARCHAR(255) NOT NULL,
  modifiedBy VARCHAR(255) NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  modifiedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  isActive TINYINT(1) NOT NULL DEFAULT '1',
  FOREIGN KEY (floor_id) REFERENCES floors(floor_id)
);

CREATE TABLE residents (
  resident_id INT AUTO_INCREMENT PRIMARY KEY,
  unit_id INT NOT NULL,
  full_name VARCHAR(100) NOT NULL,
  login_username VARCHAR(100),
  phone VARCHAR(40),
  createdBy VARCHAR(255) NOT NULL,
  modifiedBy VARCHAR(255) NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  modifiedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  isActive TINYINT(1) NOT NULL DEFAULT '1',
  FOREIGN KEY (unit_id) REFERENCES units(unit_id)
);

CREATE TABLE appliances (
  appliance_id INT AUTO_INCREMENT PRIMARY KEY,
  unit_id INT NOT NULL,
  appliance_type VARCHAR(40) NOT NULL,
  make_model VARCHAR(100),
  appliance_status VARCHAR(20) NOT NULL DEFAULT 'Working',
  last_serviced DATE,
  createdBy VARCHAR(255) NOT NULL,
  modifiedBy VARCHAR(255) NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  modifiedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  isActive TINYINT(1) NOT NULL DEFAULT '1',
  FOREIGN KEY (unit_id) REFERENCES units(unit_id)
);

CREATE TABLE tickets (
  ticket_id INT AUTO_INCREMENT PRIMARY KEY,
  ticket_number VARCHAR(30),
  unit_id INT NOT NULL,
  appliance_id INT,
  title VARCHAR(150) NOT NULL,
  details TEXT,
  severity VARCHAR(30) NOT NULL,
  ticket_status VARCHAR(20) NOT NULL DEFAULT 'Open',
  work_notes TEXT,
  createdBy VARCHAR(255) NOT NULL,
  modifiedBy VARCHAR(255) NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  modifiedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  isActive TINYINT(1) NOT NULL DEFAULT '1',
  FOREIGN KEY (unit_id) REFERENCES units(unit_id),
  FOREIGN KEY (appliance_id) REFERENCES appliances(appliance_id)
);

CREATE TABLE audit_logs (
  audit_log_id INT AUTO_INCREMENT PRIMARY KEY,
  actor_type VARCHAR(20),
  actor_ref VARCHAR(100),
  action_code VARCHAR(80) NOT NULL,
  entity_type VARCHAR(60),
  entity_ref VARCHAR(60),
  details TEXT,
  correlation_ref VARCHAR(80),
  ip_address VARCHAR(60),
  createdBy VARCHAR(255) NOT NULL,
  modifiedBy VARCHAR(255) NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  modifiedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  isActive TINYINT(1) NOT NULL DEFAULT '1'
);

