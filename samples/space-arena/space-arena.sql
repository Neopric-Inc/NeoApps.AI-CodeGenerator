CREATE TABLE pilots (
  pilot_id INT AUTO_INCREMENT PRIMARY KEY,
  callsign VARCHAR(40) NOT NULL,
  ship_color VARCHAR(20) NOT NULL DEFAULT 'cyan',
  ship_hull VARCHAR(20) NOT NULL DEFAULT 'dart',
  createdBy VARCHAR(255) NOT NULL, modifiedBy VARCHAR(255) NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, modifiedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  isActive TINYINT(1) NOT NULL DEFAULT '1'
);
CREATE TABLE matches (
  match_id INT AUTO_INCREMENT PRIMARY KEY,
  code VARCHAR(16) NOT NULL,
  arena VARCHAR(40) NOT NULL DEFAULT 'nebula',
  status VARCHAR(20) NOT NULL DEFAULT 'open',
  createdBy VARCHAR(255) NOT NULL, modifiedBy VARCHAR(255) NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, modifiedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  isActive TINYINT(1) NOT NULL DEFAULT '1'
);
CREATE TABLE scores (
  score_id INT AUTO_INCREMENT PRIMARY KEY,
  match_id INT NOT NULL,
  callsign VARCHAR(40) NOT NULL,
  kills INT NOT NULL DEFAULT 0,
  deaths INT NOT NULL DEFAULT 0,
  createdBy VARCHAR(255) NOT NULL, modifiedBy VARCHAR(255) NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, modifiedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  isActive TINYINT(1) NOT NULL DEFAULT '1',
  FOREIGN KEY (match_id) REFERENCES matches(match_id)
);
