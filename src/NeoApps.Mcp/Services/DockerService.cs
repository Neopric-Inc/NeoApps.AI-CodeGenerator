using System.Text;

namespace NeoApps.Mcp.Services;

/// <summary>Local deployment through Docker Compose (shared infra stack + one compose project per app).</summary>
public sealed class DockerService(NeoAppsSettings settings, ProjectStore store)
{
    private const string InfraProject = "neoapps-infra";

    public static string ComposeProjectName(string app) => "neoapps-" + app.ToLowerInvariant().Replace('_', '-');
    public string AppComposeFile(string app) => Path.Combine(store.ProjectDir(app), "docker-compose.yml");

    public Task<CommandResult> InfraUpAsync(Action<string>? log, CancellationToken ct) =>
        Compose(["-f", settings.InfraComposeFile, "-p", InfraProject, "up", "-d", "--wait"], settings.RepoRoot, log, TimeSpan.FromMinutes(10), ct);

    public Task<CommandResult> InfraDownAsync(bool removeData, CancellationToken ct) =>
        Compose(["-f", settings.InfraComposeFile, "-p", InfraProject, "down", .. (removeData ? new[] { "-v" } : [])], settings.RepoRoot, null, TimeSpan.FromMinutes(5), ct);

    public Task<CommandResult> InfraStatusAsync(CancellationToken ct) =>
        Compose(["-f", settings.InfraComposeFile, "-p", InfraProject, "ps", "--format", "table {{.Service}}\t{{.State}}\t{{.Status}}\t{{.Ports}}"], settings.RepoRoot, null, TimeSpan.FromMinutes(1), ct);

    public async Task<CommandResult> DeployAsync(ProjectState p, bool includeConsumer, Action<string> log, CancellationToken ct)
    {
        if (p.BackendPath is null || !Directory.Exists(p.BackendPath))
            throw new InvalidOperationException("The backend has not been generated yet. Run neoapps_create_app first.");

        var file = AppComposeFile(p.Name);
        await File.WriteAllTextAsync(file, BuildComposeFile(p, includeConsumer), ct);
        log($"Wrote {file}");

        if (!settings.SkipInfra)
        {
            var up = await InfraUpAsync(log, ct);
            if (!up.Ok) return up;
        }

        return await Compose(["-f", file, "-p", ComposeProjectName(p.Name), "up", "-d", "--build", "--remove-orphans"],
            store.ProjectDir(p.Name), log, TimeSpan.FromMinutes(30), ct);
    }

    public Task<CommandResult> StatusAsync(ProjectState p, CancellationToken ct) =>
        Compose(["-f", AppComposeFile(p.Name), "-p", ComposeProjectName(p.Name), "ps", "-a", "--format", "table {{.Service}}\t{{.State}}\t{{.Status}}\t{{.Ports}}"],
            store.ProjectDir(p.Name), null, TimeSpan.FromMinutes(1), ct);

    public Task<CommandResult> LogsAsync(ProjectState p, string? service, int tail, CancellationToken ct) =>
        Compose(["-f", AppComposeFile(p.Name), "-p", ComposeProjectName(p.Name), "logs", "--no-color", "--tail", tail.ToString(), .. (service is null ? Array.Empty<string>() : [service])],
            store.ProjectDir(p.Name), null, TimeSpan.FromMinutes(1), ct);

    public Task<CommandResult> StopAsync(ProjectState p, CancellationToken ct) =>
        Compose(["-f", AppComposeFile(p.Name), "-p", ComposeProjectName(p.Name), "down"],
            store.ProjectDir(p.Name), null, TimeSpan.FromMinutes(5), ct);

    public bool IsDeployed(ProjectState p) => File.Exists(AppComposeFile(p.Name));

    private static Task<CommandResult> Compose(string[] args, string cwd, Action<string>? log, TimeSpan timeout, CancellationToken ct) =>
        CommandRunner.RunAsync("docker", ["compose", .. args], cwd, log, timeout: timeout, ct: ct);

    private string BuildComposeFile(ProjectState p, bool includeConsumer)
    {
        var mysql = $"server={settings.DockerMySqlHost};port={settings.DockerMySqlPort};database={p.DatabaseName};" +
                    $"user={settings.MySqlUser};password={settings.MySqlPassword};TreatTinyAsBoolean=false;Convert Zero Datetime=true;";
        var sb = new StringBuilder();
        sb.AppendLine($"# Generated by the NeoApps MCP server for '{p.Name}'. Safe to edit; neoapps_deploy_app rewrites it.");
        sb.AppendLine($"name: {ComposeProjectName(p.Name)}");
        sb.AppendLine("services:");
        sb.AppendLine("  api:");
        sb.AppendLine("    build:");
        sb.AppendLine($"      context: {Quote(p.BackendPath!)}");
        sb.AppendLine("      dockerfile: Dockerfile");
        sb.AppendLine("    environment:");
        sb.AppendLine($"      ConnectionStrings__MySQLDatabase: {Quote(mysql)}");
        sb.AppendLine($"      ConnectionStrings__RabitMQ: {Quote(settings.DockerRabbitMqUrl)}");
        sb.AppendLine($"      ConnectionStrings__Redis: {Quote(settings.DockerRedis)}");
        // Production: no developer error pages; only the generated UI's origin may call the API. Swagger stays on for local use.
        sb.AppendLine("      ASPNETCORE_ENVIRONMENT: Production");
        sb.AppendLine($"      Cors__AllowedOrigins: {Quote($"http://localhost:{p.WebPort},http://127.0.0.1:{p.WebPort}")}");
        sb.AppendLine("      Swagger__Enabled: \"true\"");
        // AI assistant: the key comes from the environment of whoever runs the deploy; never written to disk.
        sb.AppendLine("      ANTHROPIC_API_KEY: ${ANTHROPIC_API_KEY:-}");
        sb.AppendLine("    volumes:");
        sb.AppendLine("      - app_data:/app/App_Data");
        sb.AppendLine("    ports:");
        sb.AppendLine($"      - \"{p.ApiPort}:8080\"");
        sb.AppendLine("    restart: unless-stopped");
        if (includeConsumer)
        {
            sb.AppendLine("  consumer:");
            sb.AppendLine("    build:");
            sb.AppendLine($"      context: {Quote(p.BackendPath!)}");
            sb.AppendLine("      dockerfile: Dockerfile-Consumer");
            sb.AppendLine("    environment:");
            sb.AppendLine($"      ConnectionStrings__MySQLDatabase: {Quote(mysql)}");
            sb.AppendLine($"      ConnectionStrings__RabitMQ: {Quote(settings.DockerRabbitMqUrl)}");
            // the consumer calls the API as the app admin; credentials come from the project, not from appsettings
            sb.AppendLine($"      AppSettings__DefaultTokenUsername: {Quote(p.AdminUsername ?? "")}");
            sb.AppendLine($"      AppSettings__DefaultTokenPassword: {Quote(p.AdminPassword ?? "")}");
            sb.AppendLine("    restart: unless-stopped");
        }
        if (p.FrontendPath is not null && Directory.Exists(p.FrontendPath))
        {
            sb.AppendLine("  web:");
            sb.AppendLine("    build:");
            sb.AppendLine($"      context: {Quote(p.FrontendPath)}");
            sb.AppendLine("    ports:");
            sb.AppendLine($"      - \"{p.WebPort}:80\"");
            sb.AppendLine("    depends_on: [api]");
            sb.AppendLine("    restart: unless-stopped");
        }
        sb.AppendLine("volumes:");
        sb.AppendLine("  app_data:");
        sb.AppendLine("networks:");
        sb.AppendLine("  default:");
        sb.AppendLine($"    name: {settings.DockerNetwork}");
        sb.AppendLine("    external: true");
        return sb.ToString();
    }

    private static string Quote(string s) => "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
}
